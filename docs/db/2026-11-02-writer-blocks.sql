-- Non-destructive, server-only moderation control.
CREATE TABLE IF NOT EXISTS public.user_blocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "blockerId" integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    "blockedId" integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    "createdAt" timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT user_blocks_unique_pair UNIQUE ("blockerId", "blockedId"),
    CONSTRAINT user_blocks_not_self CHECK ("blockerId" <> "blockedId")
);
CREATE INDEX IF NOT EXISTS idx_user_blocks_blocked_id ON public.user_blocks ("blockedId");
ALTER TABLE public.user_blocks ENABLE ROW LEVEL SECURITY;
-- No anon/authenticated grants or policies; only the authenticated Express backend accesses it.
