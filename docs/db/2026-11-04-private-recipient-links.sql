-- SendTheLetter recipient-only links (additive migration, 2026-11-04).
-- Run only after a confirmed backup / restore plan; app API connects as a trusted server role.
-- No existing letters, users, or media are changed.
BEGIN;
CREATE TABLE IF NOT EXISTS public.letter_recipient_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "letterId" INTEGER NOT NULL REFERENCES public.letters(id) ON DELETE CASCADE,
  "tokenHash" CHAR(64) NOT NULL UNIQUE,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  "revokedAt" TIMESTAMPTZ,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT letter_recipient_links_token_format CHECK ("tokenHash" ~ '^[0-9a-f]{64}$')
);
CREATE INDEX IF NOT EXISTS recipient_links_letter_active_idx
  ON public.letter_recipient_links ("letterId", "expiresAt") WHERE "revokedAt" IS NULL;
ALTER TABLE public.letter_recipient_links ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.letter_recipient_links FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.letter_recipient_links_id_seq FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS public.letter_recipient_replies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "linkId" BIGINT NOT NULL UNIQUE REFERENCES public.letter_recipient_links(id) ON DELETE CASCADE,
  "letterId" INTEGER NOT NULL REFERENCES public.letters(id) ON DELETE CASCADE,
  "displayName" VARCHAR(60),
  reaction VARCHAR(15) NOT NULL CHECK (reaction IN ('heart','hug','smile','thanks','star')),
  message VARCHAR(600),
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS recipient_replies_owner_idx
  ON public.letter_recipient_replies ("letterId", "createdAt" DESC);
ALTER TABLE public.letter_recipient_replies ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.letter_recipient_replies FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.letter_recipient_replies_id_seq FROM PUBLIC, anon, authenticated;

-- Changing the visibility or archival status permanently revokes existing links;
-- restored private letters must require a fresh author-controlled invitation.
CREATE OR REPLACE FUNCTION public.revoke_letter_recipient_links_on_hide()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, public AS $$
BEGIN
  IF (NEW."isPublic" OR NEW."isArchived" OR NEW.status <> 'published') THEN
    UPDATE public.letter_recipient_links SET "revokedAt" = now()
    WHERE "letterId" = NEW.id AND "revokedAt" IS NULL;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS revoke_letter_recipient_links_on_hide ON public.letters;
CREATE TRIGGER revoke_letter_recipient_links_on_hide
  AFTER UPDATE OF "isPublic", "isArchived", status ON public.letters
  FOR EACH ROW EXECUTE FUNCTION public.revoke_letter_recipient_links_on_hide();
REVOKE ALL ON FUNCTION public.revoke_letter_recipient_links_on_hide() FROM PUBLIC, anon, authenticated;
COMMIT;

