-- Compatible with existing JWTs (missing tokenVersion means version 0).
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS "tokenVersion" integer NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  "tokenHash" varchar(64) NOT NULL UNIQUE,
  "expiresAt" timestamptz NOT NULL,
  "consumedAt" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS password_reset_tokens_user_created_idx
  ON public.password_reset_tokens ("userId", "createdAt" DESC);
ALTER TABLE public.password_reset_tokens ENABLE ROW LEVEL SECURITY;
